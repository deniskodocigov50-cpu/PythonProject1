# 1. Запрашиваем тип учебного материала
material_type = input("Введите тип учебного материала (книга/видео): ").strip()

# 2. Запрашиваем стоимость с проверкой на положительное число
while True:
    try:
        price_input = input("Введите стоимость материала: ").strip()
        price = float(price_input)

        if price > 0:
                break
        else:
                print("Ошибка: стоимость должна быть положительным числом. Попробуйте снова.")
    except ValueError:
        print("Ошибка: введено не число. Пожалуйста, введите корректную стоимость.")

# 3. Запрашиваем категорию материала
category = input("Введите категорию материала: ").strip()

# Форматируем вывод стоимости: убираем лишнюю точку, если число целое
if price.is_integer():
    price_display = int(price)
else:
     price_display = price

# 4. Выводим сообщение о том, что материал успешно добавлен
print("\nОжидаемый результат:")
print(f"Материал добавлен: Тип – {material_type}, Стоимость – {price_display}, Категория – {category}")
